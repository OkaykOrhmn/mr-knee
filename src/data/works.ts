export function extractTitle(caption: string): string {
  if (!caption) return "بدون عنوان";
  const lines = caption.split("\n").filter((line) => line.trim() !== "");
  const firstLine = lines[0] || "";
  if (firstLine.includes("آقای") || firstLine.includes("خانم")) {
    const match = firstLine.match(/(آقای|خانم)\s*([^\s]+)/);
    if (match) return match[2];
  }
  const words = firstLine.split(" ");
  return words.slice(0, 4).join(" ") || "بدون عنوان";
}

export function extractDescription(caption: string): string {
  if (!caption) return "";
  const cleaned = caption
    .replace(/#\S+/g, "")
    .replace(/@\S+/g, "")
    .replace(/https?:\/\/\S+/g, "")
    .split("\n")
    .filter((line) => line.trim() !== "")
    .slice(0, 3)
    .join(" ")
    .trim();
  return cleaned || caption.slice(0, 150);
}

export function determineCategory(caption: string): string {
  if (!caption) return "متفرقه";
  const text = caption.toLowerCase();
  if (
    text.includes("بازتوانی") ||
    text.includes("زانو") ||
    text.includes("acl") ||
    text.includes("مینیسک") ||
    text.includes("رباط") ||
    text.includes("جراحی") ||
    text.includes("مکانوتراپی") ||
    text.includes("تعویض مفصل")
  ) {
    return "بازتوانی زانو";
  }
  if (
    text.includes("تمرینات پیش فصل") ||
    text.includes("بدنسازی") ||
    text.includes("پیش فصل") ||
    text.includes("تمرینات بدنسازی") ||
    text.includes("تمرینات تخصصی")
  ) {
    return "بدنسازی و آمادگی";
  }
  if (text.includes("کتف") || text.includes("کمر") || text.includes("مچ پا")) {
    return "سایر آسیب‌ها";
  }
  return "متفرقه";
}

